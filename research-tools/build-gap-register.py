"""Write coverage/gaps.md: every row in coverage/matrix.csv that has not reached its target, grouped by area and level.

    python research-tools/build-gap-register.py          # rewrite
    python research-tools/build-gap-register.py --check  # fail if stale
"""
import csv
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'coverage/gaps.md'
LEVEL = {'0': 'L0 inventoried only', '1': 'L1 named in a trace', '2': 'L2 type seen in binary index', '3': 'L3 executed (partial)'}


def build():
    rows = list(csv.DictReader((ROOT / 'coverage/matrix.csv').open(encoding='utf-8', newline='')))
    total = len(rows)
    open_rows = [r for r in rows if not r['at_target']]
    lines = ['# Gap register', '', 'Generated by `research-tools/build-gap-register.py` from `coverage/matrix.csv`. Do not edit.', '',
             f'{len(open_rows)} of {total} rows have not reached their target. "At target" means the required evidence kind exists; '
             'it does not mean the item is fully reverse engineered (see each row\'s `note`).', '']
    by = defaultdict(lambda: defaultdict(list))
    for r in open_rows:
        by[r['area']][r['level']].append(r)
    for area in ('mp-page', 'mp-module', 'ledger', 'ap-vehicle', 'ap-lib', 'ap-mode'):
        if area not in by:
            continue
        lines += [f'## {area} ({sum(len(v) for v in by[area].values())} open, target {by[area][next(iter(by[area]))][0]["target"]})', '']
        for lvl in sorted(by[area]):
            names = ', '.join(r['item'] for r in sorted(by[area][lvl], key=lambda r: r['item']))
            lines += [f'- **{LEVEL[lvl]}** ({len(by[area][lvl])}): {names}']
        lines.append('')
    return '\n'.join(lines)


def main():
    text = build()
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding='utf-8') != text:
            print('STALE gaps.md')
            raise SystemExit(1)
        print('OK')
        return
    OUT.write_text(text, encoding='utf-8', newline='\n')
    print('wrote', OUT.relative_to(ROOT))


if __name__ == '__main__':
    main()
